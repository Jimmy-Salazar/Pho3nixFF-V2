export function getAdminPrsCopy(locale) {
  return COPY[locale] || COPY.es
}

export function interpolatePrCopy(text, values = {}) {
  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    String(text || "")
  )
}
