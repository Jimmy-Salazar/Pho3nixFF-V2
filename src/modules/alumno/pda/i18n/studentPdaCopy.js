export function normalizeStudentPdaLocale(locale) {
  return String(locale || "es").toLowerCase().startsWith("en") ? "en" : "es"
}

export function getStudentPdaCopy(locale) {
  return STUDENT_PDA_COPY[normalizeStudentPdaLocale(locale)]
}

export function getStudentPdaPoster(locale, year = 2026) {
  const language = normalizeStudentPdaLocale(locale)
  return `/images/pda/pda-${year}-${language}.png`
}
